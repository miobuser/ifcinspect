// Live-switchable internationalisation for IfcInspect (DE / FR / EN / IT).
//
// Design mirrors theme.ts: resolve a language on init (stored override →
// navigator language → German default), reflect it on <html lang>, persist
// to localStorage, and notify subscribers so dynamic UI can re-render.
//
// STATIC strings carry a data-i18n / data-i18n-title / data-i18n-ph /
// data-i18n-html attribute in the template HTML; applyStaticTranslations()
// walks those and fills textContent / attributes for the active language.
//
// DYNAMIC strings (built in JS at render time) call t(key, params?) directly
// and are re-rendered by the modules that own them via onLangChange().
//
// What is NOT translated (rendered verbatim as DATA):
//   - rule labels / `soll` expressions coming from
//     the active ruleset YAML / Python pruefung,
//   - the TARGET_CATALOG rule-target identifiers + any YAML content,
//   - class KEYS "K0".."K6" and GUIDs.
// The class DISPLAY names (Stirn +, Krone, …) ARE UI labels and ARE keyed.

