// ---- runtime state -------------------------------------------------------- //
let current: Lang = "de";

function isLang(v: unknown): v is Lang {
  return v === "de" || v === "fr" || v === "en" || v === "it";
}

function readStored(): Lang | null {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    return isLang(raw) ? raw : null;
  } catch {
    return null;
  }
}

function fromNavigator(): Lang | null {
  if (typeof navigator === "undefined") return null;
  const langs = navigator.languages && navigator.languages.length
    ? navigator.languages
    : [navigator.language];
  for (const l of langs) {
    const code = (l || "").slice(0, 2).toLowerCase();
    if (isLang(code)) return code;
  }
  return null;
}

/** t(key, params?) -> DICT[current][key] ?? DICT.de[key] ?? key, with {name}
 *  substitution. Missing keys fall back to German, then to the raw key so a
 *  forgotten translation is at least readable and greppable. */
export function t(key: string, params?: Record<string, string | number>): string {
  const raw = DICT[current][key] ?? DICT.de[key] ?? key;
  if (!params) return raw;
  return raw.replace(/\{(\w+)\}/g, (m, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : m,
  );
}

export function getLang(): Lang {
  return current;
}

function notify(): void {
  for (const cb of subscribers) {
    try { cb(current); } catch { /* a bad subscriber must not break others */ }
  }
}

/** Walk [data-i18n] / [data-i18n-title] / [data-i18n-ph] / [data-i18n-html]
 *  nodes within `root` and fill them for the current language. */
export function applyStaticTranslations(root: ParentNode): void {
  root.querySelectorAll<HTMLElement>("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (key) el.textContent = t(key);
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-html]").forEach((el) => {
    const key = el.getAttribute("data-i18n-html");
    if (key) el.innerHTML = t(key);
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-title]").forEach((el) => {
    const key = el.getAttribute("data-i18n-title");
    if (key) {
      const v = t(key);
      el.setAttribute("title", v);
      // Keep the custom-tooltip source attribute in sync where present.
      if (el.hasAttribute("data-tip")) el.setAttribute("data-tip", v);
      el.setAttribute("aria-label", v);
    }
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-ph]").forEach((el) => {
    const key = el.getAttribute("data-i18n-ph");
    if (key) el.setAttribute("placeholder", t(key));
  });
}

/** Persist + apply a language: store it, set <html lang>, re-translate the
 *  whole document's static nodes, and notify dynamic-content subscribers. */
export function setLang(l: Lang): void {
  if (!isLang(l)) return;
  current = l;
  try { localStorage.setItem(STORAGE_KEY, l); } catch { /* best-effort */ }
  document.documentElement.lang = l;
  applyStaticTranslations(document);
  notify();
}

/** Resolve stored → navigator → default(de), set <html lang>, return it.
 *  Does NOT notify (called before mount, like initTheme). */
export function initLang(): Lang {
  current = readStored() ?? fromNavigator() ?? "de";
  document.documentElement.lang = current;
  return current;
}

export function onLangChange(cb: (l: Lang) => void): void {
  subscribers.push(cb);
}

/** Active-language display label for a status CODE. The code itself
 *  (PASS/FAIL/WARN/INFO/SKIP) stays the source of truth for logic/CSS; this is
 *  the human-facing text only. Accepts the upper-case TS codes used by RuleCheck
 *  (PASS/FAIL/WARN/INFO) and Issue (PASS/FAIL/WARN/SKIP) as well as the raw
 *  Python lower-case values (pass/fail/warn/info/skip).
 *  INFO ("Info") and SKIP ("Übersprungen") are kept DISTINCT: INFO is a purely
 *  informative result, SKIP means the rule was not evaluated. */
export function statusLabel(code: string): string {
  switch (code) {
    case "PASS": case "pass": return t("status.pass");
    case "FAIL": case "fail": return t("status.fail");
    case "WARN": case "warn": return t("status.warn");
    case "INFO": case "info": return t("status.info");
    case "SKIP": case "skip": return t("status.skip");
    default: return code;
  }
}
